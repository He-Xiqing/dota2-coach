def normalize_language(code: str | None) -> str:
    value = (code or "").strip()
    if value in _STRINGS:
        return value
    lower = value.lower()
    for key in _STRINGS:
        if key.lower() == lower:
            return key
    return FALLBACK


def tr(language: str | None, name: str, **fmt: object) -> str:
    lang = normalize_language(language)
    table = _STRINGS.get(lang) or _STRINGS[FALLBACK]
    text = table.get(name) or _STRINGS[FALLBACK].get(name) or name
    if fmt:
        try:
            return text.format(**fmt)
        except (KeyError, IndexError):
            return text
    return text


