def ftext(key: str, **fmt: object) -> str | None:
    """非中文返回本地文案；中文返回 None 由调用方沿用原有中文句式。"""
    lang = current_language()
    if lang == "zh-CN":
        return None
    table = FIGHT.get(lang) or FIGHT["en"]
    text = table.get(key)
    if text is None:
        return None
    try:
        return text.format(**fmt)
    except (KeyError, IndexError):
        return text
