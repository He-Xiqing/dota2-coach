def t(key: str, **fmt: object) -> str:
    table = TEXTS.get(_language) or TEXTS["zh-CN"]
    text = table.get(key) or TEXTS["zh-CN"].get(key) or key
    try:
        return text.format(**fmt)
    except (KeyError, IndexError, ValueError):
        return text


